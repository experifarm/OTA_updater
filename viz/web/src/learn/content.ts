export function ct(key: string, params: Record<string, string | number> = {}): string {
  const s = dicts[getLang()][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}
